#!/usr/bin/env python3
"""Render the client release note to PDF at the page's own width.

Chrome does the rendering rather than a Python PDF library because a note can be
in any script: Arabic-script glyph joining, ZWNJ handling, RTL bidi and complex
shaping are all required somewhere, and Blink already does them. A generic PDF
writer silently emits disconnected or reversed text and reports success.

**The PDF is the screen.** Not "a paper version of the screen" - the same
document, at the same width, with the same colours. Two decisions get it there:

  WIDTH comes from the stylesheet's @page size, so the layout never reflows.
  HEIGHT is measured from the content, so the PDF is ONE continuous page.

The height decision is the one worth explaining. Cutting the note into
page-sized sheets cannot be done without gaps: cards must not be sliced, so each
break leaves whatever space the next card could not fit into - in this note that
was 440px at the foot of page 1 and 700px at the foot of page 3, against an HTML
page that has no gaps anywhere. A single page removes the question. Text stays
selectable, the file stays small, and a viewer that has to put it on paper
scales it like any other oversized page. `--paginate` restores fixed sheets for
anyone who needs them.

ONE CONTINUOUS PAGE HAS A CEILING, THOUGH: about 8,192 CSS px. Viewers built on
pdf.js draw a page into a single canvas, and a canvas side cannot exceed
16,384px - which a Retina display reaches at twice the CSS height. Past that the
PDF is still a valid file, still passes every check in this skill, and opens to
a blank window. A note that long has to be rendered with `--paginate`; this
script warns when a continuous render crosses the line.

Which is why this script drives Chrome through Playwright rather than
`chrome --headless --print-to-pdf`:

    THE COMMAND LINE CANNOT MEASURE THE CONTENT.

`--print-to-pdf` has no way to measure the note and size the page to it, and
no way to ask for `preferCSSPageSize`, so it prints whatever fixed page the
stylesheet (or, with no usable @page, the browser default - A4 portrait, about
688px of printable width, which collapses the two-column cards) gives it. The
continuous page, the one-page default, is out of reach. Measured, not assumed:
a file that reports `page: 840x1188pt` through Playwright has reported
`595x842pt` through the CLI.

Order of preference: the Python `playwright` package (no driver file), then a
Node playwright-core found via NODE_PATH or a configured clone, then the CLI -
which says loudly what it costs. All three honour UX_EXECUTABLE_PATH /
UX_BROWSER_CHANNEL, so a browser already on disk is used when the download is
blocked.

The font report checks what actually landed in the PDF against the design
system's own list - `allowed_families` in <design.build>/tokens.json, written by
brand-system's `brand.py build`, plus the mono stack - and names the character
that pulled in anything else.

Usage:
    python render-client-pdf.py "<releases.out>/<version> - <date>/client.html"
    ... --paginate     fixed sheets at the @page height, instead of one continuous page
    ... --hub <path>   hub root (default: walk up from the current directory)
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import platform
import re
import shutil
import subprocess
import sys

sys.dont_write_bytecode = True  # a skill does not litter its own folder with __pycache__

import tempfile
